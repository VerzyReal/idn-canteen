export function BottomNav() {
  const pathname     = usePathname();
  const totalItems   = useCartStore(s => s.getTotalItems());

  return (
    <nav className="bottom-nav safe-area-pb">
      {navItems.map((item) => {
        const isActive = pathname === item.href || (item.href !== '/' && pathname.startsWith(item.href));
        return (
          <Link key={item.href} href={item.href} className={`bottom-nav-item ${isActive ? 'active' : ''}`}>
            <span className="relative">
              {item.icon(isActive)}
              {item.href === '/checkout' && totalItems > 0 && (
                <span className="absolute -top-1.5 -right-1.5 bg-primary-500 text-white text-[10px] font-bold w-4 h-4 rounded-full flex items-center justify-center">
                  {totalItems > 9 ? '9+' : totalItems}
                </span>
              )}
            </span>
            <span className="text-[10px] font-medium">{item.label}</span>
          </Link>
        );
      })}
    </nav>
  );
}

